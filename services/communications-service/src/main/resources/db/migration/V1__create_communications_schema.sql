CREATE FUNCTION protect_approved_communication_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.workflow_status = 'APPROVED' THEN
    RAISE EXCEPTION 'Approved communication versions are immutable';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_protect_approved_communication_version BEFORE UPDATE OR DELETE ON communication_item_versions FOR EACH ROW EXECUTE FUNCTION protect_approved_communication_version();

CREATE FUNCTION protect_communication_workflow_event() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Communication workflow events are append-only';
END $$;
CREATE TRIGGER trg_protect_communication_workflow_event BEFORE UPDATE OR DELETE ON communication_workflow_events FOR EACH ROW EXECUTE FUNCTION protect_communication_workflow_event();

-- Envers audit tables mirror every business entity.
CREATE TABLE communication_categories_aud (LIKE communication_categories INCLUDING DEFAULTS);
CREATE TABLE communication_items_aud (LIKE communication_items INCLUDING DEFAULTS);
CREATE TABLE communication_item_versions_aud (LIKE communication_item_versions INCLUDING DEFAULTS);
CREATE TABLE communication_publications_aud (LIKE communication_publications INCLUDING DEFAULTS);
CREATE TABLE communication_workflow_events_aud (LIKE communication_workflow_events INCLUDING DEFAULTS);
CREATE TABLE communication_media_assets_aud (LIKE communication_media_assets INCLUDING DEFAULTS);
CREATE TABLE event_occurrences_aud (LIKE event_occurrences INCLUDING DEFAULTS);
CREATE TABLE communication_read_receipts_aud (LIKE communication_read_receipts INCLUDING DEFAULTS);

DO $$
DECLARE audit_table text;
BEGIN
  FOREACH audit_table IN ARRAY ARRAY['communication_categories_aud','communication_items_aud','communication_item_versions_aud','communication_publications_aud','communication_workflow_events_aud','communication_media_assets_aud','event_occurrences_aud','communication_read_receipts_aud']
  LOOP
    EXECUTE format('ALTER TABLE %I DROP CONSTRAINT IF EXISTS %I', audit_table, replace(audit_table, '_aud', '') || '_pkey');
    EXECUTE format('ALTER TABLE %I ADD COLUMN rev integer NOT NULL REFERENCES revinfo(rev)', audit_table);
    EXECUTE format('ALTER TABLE %I ADD COLUMN revtype smallint', audit_table);
    EXECUTE format('ALTER TABLE %I ADD PRIMARY KEY (id, rev)', audit_table);
  END LOOP;
END $$;

